create or replace function public.submit_access_request(
  p_name text,
  p_relation text,
  p_avatar text default null,
  p_bio text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $accessrequest$
declare
  v_name text := trim(coalesce(p_name,''));
  v_avatar text := trim(coalesce(p_avatar,''));
  v_bio text := trim(coalesce(p_bio,''));
  v_id bigint;
begin
  if char_length(v_name) < 1 or char_length(v_name) > 50
     or p_relation not in ('Ami(e)','Famille','Camarade de classe','Connaissance','Autre')
     or char_length(v_avatar) > 4
     or char_length(v_bio) > 250 then
    raise exception 'Demande invalide.';
  end if;

  if exists(
    select 1
    from public.list_access_codes lac
    where lac.active=true
      and lower(trim(lac.label))=lower(v_name)
  ) then
    raise exception 'Un accès actif existe déjà pour ce nom.';
  end if;

  if exists(
    select 1
    from public.access_requests ar
    where ar.status='pending'
      and lower(trim(ar.name))=lower(v_name)
  ) then
    raise exception 'Une demande est déjà en attente pour ce nom.';
  end if;

  insert into public.access_requests(name,relation,avatar,bio)
  values(v_name,p_relation,nullif(v_avatar,''),nullif(v_bio,''))
  returning id into v_id;

  return jsonb_build_object(
    'ok',true,
    'request_id',v_id,
    'status','pending'
  );
end;
