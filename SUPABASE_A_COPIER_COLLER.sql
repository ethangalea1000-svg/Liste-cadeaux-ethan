create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $audit$
declare
  row_data jsonb;
  old_data jsonb;
  actor text;
  entity_key text;
  detail text;
  action_name text;
  old_status text;
  new_status text;
begin
  row_data := case when TG_OP = 'DELETE' then to_jsonb(OLD) else to_jsonb(NEW) end;
  old_data := case when TG_OP = 'INSERT' then '{}'::jsonb else to_jsonb(OLD) end;

  actor := coalesce(
    nullif(trim(row_data->>'name'), ''),
    'Visiteur'
  );

  entity_key := coalesce(row_data->>'id', row_data->>'gift_id');

  old_status := coalesce(old_data->>'status', '');
  new_status := coalesce(row_data->>'status', '');

  if TG_OP = 'UPDATE'
     and TG_TABLE_NAME in ('gift_suggestions','fundraisers')
     and old_status <> new_status
  then
    action_name := case
      when new_status = 'approved' then 'validée'
      when new_status = 'rejected' then 'refusée'
      else 'modifiée'
    end;
  else
    action_name := case TG_OP
      when 'INSERT' then 'créée'
      when 'UPDATE' then 'modifiée'
      when 'DELETE' then 'supprimée'
      else lower(TG_OP)
    end;
  end if;

  detail := coalesce(
    nullif(trim(row_data->>'gift_name'), ''),
    nullif(trim(row_data->>'title'), ''),
    nullif(trim(row_data->>'gift_id'), ''),
    case when TG_TABLE_NAME = 'community_reactions'
      then 'Réaction ' || coalesce(row_data->>'emoji','')
    end,
    TG_TABLE_NAME
  );

  insert into public.audit_logs(actor_name, action, entity_type, entity_id, details)
  values (
    actor,
    action_name,
    case TG_TABLE_NAME
      when 'gift_suggestions' then 'Suggestion'
      when 'fundraisers' then 'Cagnotte'
      when 'contributions' then 'Participation'
      when 'messages' then 'Message'
      when 'ideas' then 'Idée'
      when 'community_posts' then 'Communauté'
      when 'community_reactions' then 'Réaction'
      when 'reservations' then 'Réservation'
      else TG_TABLE_NAME
    end,
    entity_key,
    detail
  );

  return case when TG_OP = 'DELETE' then OLD else NEW end;
end;
$audit$;

