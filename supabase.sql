create policy "Public can view gift suggestions"
on public.gift_suggestions for select
to anon
using (true);

drop policy if exists "Public can create gift suggestions" on public.gift_suggestions;
create policy "Public can create gift suggestions"
on public.gift_suggestions for insert
to anon
with check (char_length(trim(gift_name)) between 1 and 120);

