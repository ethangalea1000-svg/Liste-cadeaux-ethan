-- Participations financières annoncées (aucun paiement n'est effectué ici)
create table if not exists public.contributions (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 50),
  amount numeric(10,2) not null check (amount >= 1 and amount <= 5000),
  message text,
  created_at timestamptz not null default now()
);

alter table public.contributions enable row level security;

drop policy if exists "Public can view contributions" on public.contributions;
create policy "Public can view contributions"
on public.contributions for select
to anon
using (true);

drop policy if exists "Public can create contributions" on public.contributions;
create policy "Public can create contributions"
on public.contributions for insert
to anon
with check (
  char_length(trim(name)) between 1 and 50
  and amount >= 1
  and amount <= 5000
);

grant select, insert on table public.contributions to anon;
grant usage, select on sequence public.contributions_id_seq to anon;
